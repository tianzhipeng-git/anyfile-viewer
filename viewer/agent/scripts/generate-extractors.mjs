import { existsSync, mkdirSync, readdirSync, readFileSync, statSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const agentRoot = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const repoRoot = resolve(agentRoot, "../..");
const pluginsDir = join(repoRoot, "viewer/plugins");
const outFile = join(agentRoot, "src/generated/extractors.ts");

function extractManifestId(manifestSource) {
  const match = manifestSource.match(/\bid\s*:\s*["']([a-z0-9-]+)["']/);
  return match ? match[1] : null;
}

const entries = [];
for (const dir of readdirSync(pluginsDir).sort()) {
  const pluginRoot = join(pluginsDir, dir);
  if (!statSync(pluginRoot).isDirectory()) continue;
  const pkgPath = join(pluginRoot, "package.json");
  if (!existsSync(pkgPath)) continue;
  const pkg = JSON.parse(readFileSync(pkgPath, "utf8"));
  if (!pkg.exports?.["./extract"]) continue;
  const manifestPath = join(pluginRoot, "src/manifest.ts");
  const pluginId = existsSync(manifestPath) ? extractManifestId(readFileSync(manifestPath, "utf8")) : null;
  if (!pluginId) {
    throw new Error(`Plugin ${dir} exports ./extract but has no literal id in src/manifest.ts`);
  }
  entries.push({ pluginId, packageName: pkg.name });
}

entries.sort((a, b) => a.pluginId.localeCompare(b.pluginId));

const lines = [
  "// Auto-generated by viewer/agent/scripts/generate-extractors.mjs — do not edit manually.",
  'import type { StructuredExtractor } from "@anyfile/viewer-protocol";',
  "",
  "export const extractorLoaders: Readonly<Record<string, () => Promise<StructuredExtractor>>> = {",
  ...entries.map(
    ({ pluginId, packageName }) =>
      `  ${JSON.stringify(pluginId)}: async () => (await import(${JSON.stringify(`${packageName}/extract`)})).default,`,
  ),
  "};",
  "",
  "export function hasExtractor(pluginId: string): boolean {",
  "  return Object.prototype.hasOwnProperty.call(extractorLoaders, pluginId);",
  "}",
  "",
];

mkdirSync(dirname(outFile), { recursive: true });
writeFileSync(outFile, lines.join("\n"), "utf8");
console.log(`Generated ${outFile} (${entries.length} extractor(s))`);
