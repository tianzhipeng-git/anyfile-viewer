import { existsSync, mkdirSync, readdirSync, readFileSync, statSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const agentRoot = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const repoRoot = resolve(agentRoot, "../..");
const pluginsDir = join(repoRoot, "viewer/plugins");
const outFile = join(agentRoot, "renderer-host/src/generated/loaders.ts");

function extractManifestId(manifestSource) {
  const match = manifestSource.match(/\bid\s*:\s*["']([a-z0-9-]+)["']/);
  return match ? match[1] : null;
}

const entries = [];
for (const dir of readdirSync(pluginsDir).sort()) {
  const pluginRoot = join(pluginsDir, dir);
  if (!statSync(pluginRoot).isDirectory()) continue;
  const manifestPath = join(pluginRoot, "src/manifest.ts");
  const indexPath = join(pluginRoot, "src/index.ts");
  if (!existsSync(manifestPath) || !existsSync(indexPath)) continue;
  const pluginId = extractManifestId(readFileSync(manifestPath, "utf8"));
  if (!pluginId) continue;
  entries.push({ pluginId, dir });
}

entries.sort((a, b) => a.pluginId.localeCompare(b.pluginId));

const lines = [
  "// Auto-generated by viewer/agent/scripts/generate-renderer-loaders.mjs — do not edit manually.",
  'import type { FileViewerPlugin } from "@anyfile/viewer-protocol";',
  "",
  "function pickPlugin(mod: Record<string, unknown>, id: string): FileViewerPlugin {",
  "  for (const value of Object.values(mod)) {",
  '    if (value && typeof value === "object" && "manifest" in value && "open" in value) {',
  "      const candidate = value as FileViewerPlugin;",
  '      if (candidate.manifest?.id === id && typeof candidate.open === "function") {',
  "        return candidate;",
  "      }",
  "    }",
  "  }",
  '  throw new Error(`Plugin module for "${id}" does not export a matching FileViewerPlugin.`);',
  "}",
  "",
  "export const browserViewerLoaders: Readonly<Record<string, () => Promise<FileViewerPlugin>>> = {",
  ...entries.map(
    ({ pluginId, dir }) =>
      `  ${JSON.stringify(pluginId)}: async () => pickPlugin(await import(${JSON.stringify(`../../../../plugins/${dir}/src/index`)}) as Record<string, unknown>, ${JSON.stringify(pluginId)}),`,
  ),
  "};",
  "",
];

mkdirSync(dirname(outFile), { recursive: true });
writeFileSync(outFile, lines.join("\n"), "utf8");
console.log(`Generated ${outFile} (${entries.length} browser loader(s))`);
