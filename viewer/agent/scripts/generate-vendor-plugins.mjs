import { existsSync, mkdirSync, readdirSync, readFileSync, statSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const agentRoot = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const repoRoot = resolve(agentRoot, "../..");
const pluginsDir = join(repoRoot, "viewer/plugins");
const outFile = join(agentRoot, "src/generated/vendor-plugins.ts");

function extractManifestId(manifestSource) {
  const match = manifestSource.match(/\bid\s*:\s*["']([a-z0-9-]+)["']/);
  return match ? match[1] : null;
}

const entries = [];
for (const dir of readdirSync(pluginsDir).sort()) {
  const pluginRoot = join(pluginsDir, dir);
  if (!statSync(pluginRoot).isDirectory()) continue;
  const policyPath = join(pluginRoot, "policy.json");
  const manifestPath = join(pluginRoot, "src/manifest.ts");
  if (!existsSync(policyPath) || !existsSync(manifestPath)) continue;
  const pluginId = extractManifestId(readFileSync(manifestPath, "utf8"));
  if (!pluginId) continue;

  const policy = JSON.parse(readFileSync(policyPath, "utf8"));
  const patterns = new Set();
  for (const set of policy.runtimeSets ?? []) {
    for (const pattern of set.assetPatterns ?? []) {
      if (typeof pattern === "string" && pattern.startsWith("public/vendor/")) {
        patterns.add(pattern.slice("public/vendor/".length));
      }
    }
  }
  if (patterns.size > 0) {
    entries.push({ pluginId, patterns: [...patterns].sort() });
  }
}

entries.sort((a, b) => a.pluginId.localeCompare(b.pluginId));

const lines = [
  "// Auto-generated by viewer/agent/scripts/generate-vendor-plugins.mjs — do not edit manually.",
  "",
  "export const pluginVendorPatterns: Readonly<Record<string, readonly string[]>> = {",
  ...entries.map(({ pluginId, patterns }) => `  ${JSON.stringify(pluginId)}: ${JSON.stringify(patterns)},`),
  "};",
  "",
];

mkdirSync(dirname(outFile), { recursive: true });
writeFileSync(outFile, lines.join("\n"), "utf8");
console.log(`Generated ${outFile} (${entries.length} plugin(s) with /vendor/ assets)`);
